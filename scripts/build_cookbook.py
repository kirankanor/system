#!/usr/bin/env python
"""Generate `cookbook/data.js` from canonical manifests (FR-23, NFR-6).

One source, no drift
--------------------
Every field in the output is read from a `manifest.json` or from a file the
manifest names. Nothing about a component is written here by hand, so the
cookbook cannot describe a component the registry does not have, and cannot
miss one it does.

Determinism is the whole point of `--check`
-------------------------------------------
AC-6 asks that regenerating against unchanged manifests reproduces the
committed file byte-for-byte. That is what makes a drift check meaningful at
all: if the generator stamped a timestamp or iterated a hash-ordered set, every
run would differ and a non-zero exit would tell you nothing. So components are
sorted by id, categories follow a fixed pipeline order, and no clock is read.

`--check` also names the differing component, because "data.js is out of date"
sends someone to diff a 20KB file by eye, while "fixed-size-chunker differs"
sends them to one manifest.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "src"
if str(SRC) not in sys.path:
    sys.path.insert(0, str(SRC))

from rag_code_library.registry import Registry

COOKBOOK = REPO / "cookbook"
OUTPUT = COOKBOOK / "data.js"

#: Pipeline order, not alphabetical: the sidebar reads top to bottom as data
#: moves through the system. Only categories that actually have components are
#: emitted, so an area with no manifests does not appear as an empty section.
CATEGORIES: tuple[tuple[str, str, str, str], ...] = (
    ("ingestion", "Ingestion", "\u21e9", "Get documents into text a pipeline can use."),
    ("chunking", "Chunking", "\u2702", "Split text into pieces that retrieve well."),
    ("embeddings", "Embeddings", "\u25a6", "Turn text into vectors."),
    ("storage", "Storage", "\u25a4", "Keep documents and vectors, and get them back."),
    ("retrieval", "Retrieval", "\u2315", "Find the chunks that answer a query."),
    ("reranking", "Reranking", "\u25a5", "Reorder retrieved chunks by real relevance."),
    ("context", "Context Building", "\u25a4", "Assemble what the model will actually read."),
    ("generation", "Generation", "\u2b50", "Build prompts, and hold answers to the evidence."),
    ("evaluation", "Evaluation", "\u2713", "Measure retrieval and answer quality."),
    ("security", "Security", "\u2b21", "Keep untrusted input out of the pipeline."),
    ("config", "Configuration", "\u2699", "Settings that survive being copied."),
)

HEADER = (
    "// Generated by scripts/build_cookbook.py from canonical component manifests.\n"
    "// Do not edit by hand: edit the manifest or the source, then regenerate.\n"
    "// `python scripts/build_cookbook.py --check` fails if this file drifts.\n"
)


def readme_sections(markdown: str) -> dict[str, str]:
    """Split a README into ``## heading`` -> body.

    Fenced code blocks are skipped, because a README's own example code
    routinely contains a line starting with ``##`` and would otherwise be
    mistaken for a section boundary -- silently truncating the section below it.
    """
    sections: dict[str, list[str]] = {}
    current: list[str] | None = None
    in_fence = False
    for line in markdown.splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
            if current is not None:
                current.append(line)
            continue
        if not in_fence and line.startswith("## "):
            current = sections.setdefault(line[3:].strip(), [])
            continue
        if current is not None:
            current.append(line)
    return {title: "\n".join(lines).strip() for title, lines in sections.items()}


def _first_section(sections: dict[str, str], *titles: str) -> str:
    """The first non-empty section matching any of ``titles``.

    Prefix as well as exact, because the READMEs agree on the words but not on
    the punctuation around them: two components head the section
    ``Known limitation: characters, not tokens`` rather than
    ``Known limitations``. Matching exactly would drop both silently and the
    site would render "Not recorded" for a section that plainly is recorded --
    the failure mode that matters here, because nothing else would flag it.
    """
    for title in titles:
        for name, body in sections.items():
            if body and (name == title or name.startswith(title)):
                return body
    return ""


def component_record(entry) -> dict[str, object]:
    """One component, from its manifest and the files that manifest names."""
    manifest = entry.manifest
    sections = readme_sections(
        (entry.directory / manifest.documentation).read_text(encoding="utf-8")
    )
    source = (entry.directory / manifest.source).read_text(encoding="utf-8")

    requires = f">={manifest.requires_python.min}"
    if manifest.requires_python.max:
        requires += f", <{manifest.requires_python.max}"

    return {
        "id": manifest.id,
        "name": manifest.name,
        "category": manifest.category,
        "status": manifest.status,
        "version": manifest.version,
        "description": manifest.description,
        "destination": manifest.destination,
        "install": manifest.install,
        "requires_python": requires,
        "dependencies": list(manifest.dependencies),
        "required_packages": [
            f"{p.name}{p.specifier}" for p in manifest.required_packages
        ],
        "optional_packages": [
            f"{p.name}{p.specifier}" for p in manifest.optional_packages
        ],
        "external_services": [
            {"name": s.name, "env_vars": list(s.env_vars), "notes": s.notes}
            for s in manifest.external_services
        ],
        # Readme prose, kept as markdown and rendered by the site. Purpose
        # stands in for "when would I reach for this", which is what a
        # cookbook's reader is actually asking.
        "purpose": _first_section(sections, "Purpose", "Quick use", "Usage"),
        "api": sections.get("Public API", ""),
        # FR-21 asks for a code *example*, which is not the same thing as the
        # source: the source says what it does, the example says how you call
        # it. Both are shown.
        "example": sections.get("Example", ""),
        "tradeoffs": sections.get("Trade-offs", ""),
        "limitations": _first_section(sections, "Known limitation", "Limitations"),
        "code": source,
        "source_path": (entry.directory / manifest.source)
        .relative_to(REPO)
        .as_posix(),
        "readme_path": (entry.directory / manifest.documentation)
        .relative_to(REPO)
        .as_posix(),
        "test_path": (entry.directory / manifest.tests).relative_to(REPO).as_posix(),
    }


def build() -> dict[str, object]:
    """The payload, built the same way on every run."""
    registry = Registry.load(REPO / "components")
    if not registry.ok:
        for issue in registry.issues:
            print(f"ERROR: {issue}", file=sys.stderr)
        raise SystemExit(1)

    records = [component_record(entry) for entry in registry]
    records.sort(key=lambda record: record["id"])

    present = {record["category"] for record in records}
    categories = [
        {"id": cid, "name": name, "icon": icon, "description": blurb}
        for cid, name, icon, blurb in CATEGORIES
        if cid in present
    ]
    unknown = present - {cid for cid, *_ in CATEGORIES}
    if unknown:
        raise SystemExit(f"manifests declare categories with no presentation: {unknown}")

    return {"categories": categories, "components": records}


def render(payload: dict[str, object]) -> str:
    """The exact bytes to write. Pure, so `--check` and a build agree."""
    body = json.dumps(payload, indent=2, ensure_ascii=True)
    return f"{HEADER}window.RAG_COOKBOOK_DATA = {body};\n"


def differences(committed: str, generated: str) -> list[str]:
    """Which components differ, rather than "a 20KB file differs"."""
    if committed == generated:
        return []

    def parse(text: str) -> dict[str, object] | None:
        try:
            return json.loads(text.split("=", 1)[1].strip().rstrip(";").strip())
        except (IndexError, json.JSONDecodeError):
            return None

    before, after = parse(committed), parse(generated)
    if before is None or after is None:
        return ["<data.js is not parseable, so no single component can be named>"]

    left = {c["id"]: c for c in before.get("components", [])}
    right = {c["id"]: c for c in after.get("components", [])}
    changed = [
        cid for cid in sorted(set(left) | set(right)) if left.get(cid) != right.get(cid)
    ]
    if before.get("categories") != after.get("categories"):
        changed.insert(0, "<the category list itself>")
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify cookbook/data.js matches the manifests; write nothing",
    )
    args = parser.parse_args(argv)

    generated = render(build())

    if args.check:
        if not OUTPUT.is_file():
            print(f"{OUTPUT} does not exist; run scripts/build_cookbook.py", file=sys.stderr)
            return 1
        committed = OUTPUT.read_text(encoding="utf-8")
        changed = differences(committed, generated)
        if not changed:
            print(f"OK: {OUTPUT.name} matches the canonical manifests byte-for-byte")
            return 0
        print(
            f"DRIFT: {OUTPUT.name} is stale. Changed: {', '.join(changed)}",
            file=sys.stderr,
        )
        print("Regenerate with: python scripts/build_cookbook.py", file=sys.stderr)
        return 1

    OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
    payload = json.loads(generated.split("=", 1)[1].strip().rstrip(";").strip())
    print(
        f"Wrote {OUTPUT.relative_to(REPO).as_posix()}: "
        f"{len(payload['components'])} components across "
        f"{len(payload['categories'])} categories"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
